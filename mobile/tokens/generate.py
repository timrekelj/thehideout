# ---------------------------------------------------------------- main


def main(argv):
    check = "--check" in argv
    with open(os.path.join(HERE, "tokens.json"), encoding="utf-8") as f:
        tokens = json.load(f)
    outputs = {SWIFT_OUT: gen_swift(tokens), KOTLIN_OUT: gen_kotlin(tokens)}
    stale = []
    for path, text in outputs.items():
        rel = os.path.relpath(path, os.path.dirname(ROOT))
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    current = f.read()
            except FileNotFoundError:
                current = None
            if current != text:
                stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print(f"wrote {rel} ({len(text.encode()) // 1024} KiB)")
    if check:
        if stale:
            print(
                "stale generated files (run `python3 -I mobile/tokens/generate.py`):",
                file=sys.stderr,
            )
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            return 1
        print("generated design tokens are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
