    w(
        "    /// ratio to follow Dynamic Type). Falls back to the system font if the fonts are not registered."
    )
    w("    public func font(scale: CGFloat = 1) -> Font {")
    w(
        "        Font(DesignFonts.ctFont(size: size * scale, weight: weight, mono: mono))"
    )
    w("    }")
    w("}")
    w("")
    w(
        "/// The type scale at one text size (desktop's `type_::SCALE`, sizes and line heights scaled)."
    )
    w("public struct TypeRamp: Equatable, Sendable {")
    for n in style_names:
        w(f"    public let {camel(n)}: TypeStyle")
    w("    /// Medium weight control text (buttons).")
    w("    public let controlStrong: TypeStyle")
    w("}")
    w("")
    w("public enum DesignFonts {")
    w(f'    public static let uiFamily = "{t["type"]["families"]["ui"]}"')
    w(f'    public static let monoFamily = "{t["type"]["families"]["mono"]}"')
