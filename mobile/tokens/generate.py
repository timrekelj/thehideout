    w("")
    w("    public init() {}")
    w("")
    w("    public init(from decoder: Decoder) throws {")
    w("        let c = try decoder.container(keyedBy: CodingKeys.self)")
    w("        self.init()")
    w(
        "        accent = try c.decodeIfPresent(AccentPreset.self, forKey: .accent) ?? accent"
    )
    w(
        "        background = try c.decodeIfPresent(BackgroundPreset.self, forKey: .background) ?? background"
    )
    w(
        "        appearance = try c.decodeIfPresent(AppearanceChoice.self, forKey: .appearance) ?? appearance"
    )
    w("        tint = try c.decodeIfPresent(Bool.self, forKey: .tint) ?? tint")
    w(
        "        contrast = try c.decodeIfPresent(ContrastLevel.self, forKey: .contrast) ?? contrast"
    )
    w(
        "        density = try c.decodeIfPresent(Density.self, forKey: .density) ?? density"
    )
