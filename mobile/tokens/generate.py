    n_tokens = len(order)
    chan_keys = t["channelPalette"]["keys"]
    accents = t["axes"]["accents"]
    backgrounds = t["axes"]["backgrounds"]
    looks = packed_looks(t)
    L = []
    w = L.append

    w(f"// {HEADER}")
    w("// swiftlint:disable all")
    w("")
    w("import CoreText")
    w("import SwiftUI")
    w("")

    # --- enums
    w("// MARK: - Choices (the ThemeSpec axes; raw values are desktop's serde names)")
    w("")
    w(
        "public enum AccentPreset: String, CaseIterable, Codable, Sendable, Identifiable {"
    )
