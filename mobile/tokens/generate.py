# ---------------------------------------------------------------- helpers


def camel(s):
    parts = s.replace("-", "_").split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(s):
    c = camel(s)
    return c[:1].upper() + c[1:]


def num(v):
    """Shortest literal for a JSON number: 12.0 -> '12', 0.05 -> '0.05'."""
    if isinstance(v, bool):
        raise ValueError(v)
    if float(v) == int(v):
        return str(int(v))
    return repr(float(v))


def hex8(h):
    """'#rrggbb' or '#rrggbbaa' -> 'RRGGBBAA'."""
    h = h.lstrip("#")
    if len(h) == 6:
        h += "ff"
    assert len(h) == 8, h
    return h.upper()


def metric_keys(tokens):
    return [
        (d, t) for d in tokens["axes"]["densities"] for t in tokens["axes"]["textSizes"]
    ]


def look_key(tokens, a, b, dark, tint, high):
    return "/".join(
        [
            a,
            b,
            "dark" if dark else "light",
            "tint" if tint else "plain",
            "high" if high else "standard",
        ]
    )


def packed_looks(tokens):
    """One string per look, in desktop's `look_index` order:
    ((((accent * 5 + background) * 2 + dark) * 2 + tint) * 2 + high).
    Each string is the colour tokens (tokenOrder) then 12 channel keys x (ink, text), as RRGGBBAA."""
    order = tokens["tokenOrder"]
    keys = tokens["channelPalette"]["keys"]
    out = []
    for a in tokens["axes"]["accents"]:
        for b in tokens["axes"]["backgrounds"]:
            for dark in (False, True):
                for tint in (False, True):
                    for high in (False, True):
                        k = look_key(tokens, a["key"], b["key"], dark, tint, high)
                        toks = tokens["looks"][k]
                        pal = tokens["channelPalette"]["looks"][k]
                        s = "".join(hex8(toks[n]) for n in order)
                        s += "".join(
                            hex8(pal[c]["ink"]) + hex8(pal[c]["text"]) for c in keys
                        )
                        out.append(s)
    return out


