    w("    public var displayName: String { rawValue.capitalized }")
    w("}")
    w("")
    w("public enum Density: String, CaseIterable, Codable, Sendable, Identifiable {")
    for c in t["axes"]["densities"]:
        w(f'    case {c} = "{c}"')
    w("    public var id: String { rawValue }")
    w("    public var displayName: String { rawValue.capitalized }")
    w("}")
    w("")
    w("public enum TextSize: String, CaseIterable, Codable, Sendable, Identifiable {")
    for c in t["axes"]["textSizes"]:
        w(f'    case p{c} = "{c}"')
    w("    public var id: String { rawValue }")
    w('    public var displayName: String { rawValue + "%" }')
    w("    /// The factor on every font size and line height.")
    w("    public var factor: CGFloat {")
    w("        switch self {")
    for c in t["axes"]["textSizes"]:
        w(f"        case .p{c}: {num(t['axes']['textSizeFactors'][c])}")
    w("        }")
    w("    }")
    w("}")
    w("")

    # --- spec
    d = t["defaults"]
    w("// MARK: - ThemeSpec")
    w("")
    w(
        "/// Everything a user can choose about the look (mirrors desktop's `ThemeSpec`). Presets only."
    )
    w("public struct ThemeSpec: Equatable, Hashable, Codable, Sendable {")
    w(f"    public var accent: AccentPreset = .{camel(d['accent'])}")
    w(f"    public var background: BackgroundPreset = .{camel(d['background'])}")
    w(f"    public var appearance: AppearanceChoice = .{d['appearance']}")
    w(f"    public var tint: Bool = {str(d['tint']).lower()}")
    w(f"    public var contrast: ContrastLevel = .{d['contrast']}")
