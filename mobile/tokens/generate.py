    w("    }")
    w("")
    w("    private enum CodingKeys: String, CodingKey {")
    w("        case accent, background, appearance, tint, contrast, density")
    w('        case textSize = "text_size"')
    w("    }")
    w("")
    w(
        f"    /// Index among the {len(looks)} looks (appearance only decides `dark`), as desktop's `look_index`."
    )
    w("    func lookIndex(dark: Bool) -> Int {")
    w("        var i = AccentPreset.allCases.firstIndex(of: accent)!")
    w(
        f"        i = i * {len(backgrounds)} + BackgroundPreset.allCases.firstIndex(of: background)!"
    )
    w("        i = i * 2 + (dark ? 1 : 0)")
    w("        i = i * 2 + (tint ? 1 : 0)")
    w("        return i * 2 + (contrast == .high ? 1 : 0)")
    w("    }")
    w("}")
    w("")

    # --- colors
    w("// MARK: - Resolved colours")
    w("")
    w("public struct ChannelColor: Equatable, Sendable {")
    w("    /// Icon ink, dots and swatches (3:1 non-text contrast). Never for text.")
    w("    public let ink: Color")
